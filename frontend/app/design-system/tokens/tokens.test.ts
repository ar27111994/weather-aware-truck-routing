import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { generateTokenFiles } from "../../../scripts/tokens/generate.ts";
import { tokens } from "./tokens";

const read = (name: string): string => readFileSync(new URL(name, import.meta.url), "utf8");

const source: unknown = JSON.parse(read("./tokens.json"));
const generated = generateTokenFiles(source);

/**
 * Flattens token CSS to `context | declaration` lines: comments dropped, line endings and the
 * `1.0` vs `1` number spelling normalised (same CSS value), so two files compare by meaning.
 */
function declarationsOf(css: string): string[] {
  const context: string[] = [];
  const declarations: string[] = [];
  for (const raw of css.replaceAll("\r\n", "\n").split("\n")) {
    const line = raw.trim();
    if (line === "" || line.startsWith("/*")) {
      continue;
    }
    if (line.endsWith("{")) {
      context.push(line.slice(0, -1).trim());
    } else if (line === "}") {
      context.pop();
    } else {
      const normalised = line.replace(/(?<![\d.])(\d+)\.0+(?!\d)/g, "$1");
      declarations.push(`${context.join(" > ")} | ${normalised}`);
    }
  }
  return declarations;
}

describe("generated token files", () => {
  it("tokens.css is committed in sync with tokens.json (run `pnpm tokens` after editing it)", () => {
    expect(read("./tokens.css")).toBe(generated.css);
  });

  it("tokens.ts is committed in sync with tokens.json (run `pnpm tokens` after editing it)", () => {
    expect(read("./tokens.ts")).toBe(generated.ts);
  });

  it("every file written by the generator carries the generated-file banner", () => {
    expect(read("./tokens.css")).toMatch(/^\/\* GENERATED by /);
    expect(read("./tokens.ts")).toMatch(/^\/\* GENERATED by /);
  });
});

describe("equivalence with the design seat's output (.planning/design, verbatim snapshot)", () => {
  // The design's dark-by-preference block is `:root:not([data-theme])`. This app also stores the
  // explicit `system` choice as `data-theme="system"` and lets CSS resolve it, so the generated
  // block lists that selector too. It is the only difference; the declarations are identical.
  const SYSTEM_SELECTOR = ', :root[data-theme="system"]';

  it("tokens.css declares the same custom properties, in the same blocks and order", () => {
    const reference = read("./__fixtures__/design-contract.tokens.css");

    expect(declarationsOf(generated.css.replace(SYSTEM_SELECTOR, ""))).toEqual(
      declarationsOf(reference),
    );
  });

  it("adds the system selector to the preference block, and nowhere else", () => {
    expect(generated.css.split(SYSTEM_SELECTOR)).toHaveLength(2);
    expect(generated.css).toContain(
      '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]), :root[data-theme="system"] {',
    );
  });

  it("tokens.ts resolves every token to the same literal as tokens.resolved.json", () => {
    const reference: unknown = JSON.parse(
      read("./__fixtures__/design-contract.tokens.resolved.json"),
    );

    expect(tokens).toEqual(reference);
  });

  it("reports the counts of the design contract: 360 tokens, 416 variables, 94 dark overrides", () => {
    expect(generated.stats).toEqual({ tokens: 360, cssVariables: 416, darkOverrides: 94 });
  });
});

describe("design contract anchors (DESIGN.md section 4: the risk ladder)", () => {
  it.each([
    ["low", "#128460", "#91DBAB"],
    ["moderate", "#7A6000", "#DDAB46"],
    ["high", "#893E00", "#F2823B"],
    ["severe", "#8C001C", "#F25855"],
    ["no-travel", "#580055", "#CA4CA8"],
    ["unknown", "#656562", "#9F9F9B"],
  ] as const)("risk %s fills are %s (light) and %s (dark)", (level, light, dark) => {
    expect(tokens.light[`risk-${level}-fill`]).toBe(light);
    expect(tokens.dark[`risk-${level}-fill`]).toBe(dark);
  });

  it("the accent is ink: paper-black in light, paper-white in dark", () => {
    expect(tokens.light["color-ink-default"]).toBe("#141412");
    expect(tokens.dark["color-ink-default"]).toBe("#FAFAF7");
  });
});
