import { describe, expect, it } from "vitest";

import { generateTokenFiles, roundHalfToEven, TokenError } from "./generate.ts";

const hex = (value: string): Record<string, unknown> => ({
  colorSpace: "srgb",
  components: [0, 0, 0],
  alpha: 1,
  hex: value,
});
const px = (value: number): Record<string, unknown> => ({ value, unit: "px" });
const dark = (value: unknown): Record<string, unknown> => ({
  "dev.haulcast": { modes: { dark: value } },
});

/** Tokens grouped by tier, the way tokens.json nests them. */
function documentOf(tiers: {
  primitive?: Record<string, unknown>;
  semantic?: Record<string, unknown>;
  component?: Record<string, unknown>;
}): Record<string, unknown> {
  return { $description: "ignored metadata", ...tiers };
}

const ink = { $type: "color", $value: hex("#141412") };
const paper = { $type: "color", $value: hex("#FEFEFA") };

function without(object: Record<string, unknown>, key: string): Record<string, unknown> {
  return Object.fromEntries(Object.entries(object).filter(([name]) => name !== key));
}

describe("generateTokenFiles: CSS structure", () => {
  const generated = generateTokenFiles(
    documentOf({
      primitive: { color: { ink, paper } },
      semantic: {
        color: {
          surface: {
            page: {
              $type: "color",
              $value: "{primitive.color.paper}",
              $extensions: dark("{primitive.color.ink}"),
            },
          },
        },
      },
      component: {
        button: { primary_bg: { $type: "color", $value: "{semantic.color.surface.page}" } },
      },
    }),
  );

  it("maps tiers to prefixes and writes aliases as var() references", () => {
    expect(generated.css).toContain("  --p-color-ink: #141412;");
    expect(generated.css).toContain("  --color-surface-page: var(--p-color-paper);");
    expect(generated.css).toContain("  --c-button-primary-bg: var(--color-surface-page);");
  });

  it("emits the light block, the dark block and the system-preference block", () => {
    const lines = generated.css.split("\n");
    expect(lines).toContain("@layer tokens {");
    expect(lines).toContain(":root {");
    expect(lines).toContain("  color-scheme: light;");
    expect(lines).toContain(':root[data-theme="dark"] {');
    expect(lines).toContain("@media (prefers-color-scheme: dark) {");
    expect(lines).toContain("  :root:not([data-theme]) {");
    expect(generated.css.endsWith("}\n")).toBe(true);
  });

  it("writes dark overrides to both the explicit dark block and the system-preference block", () => {
    const override = "--color-surface-page: var(--p-color-ink);";
    expect(generated.css).toContain(`\n  ${override}\n`);
    expect(generated.css).toContain(`\n    ${override}\n`);
  });

  it("does not repeat mode-independent tokens in the dark blocks", () => {
    expect(generated.css.match(/--p-color-ink:/g)).toHaveLength(1);
  });

  it("counts tokens, light variables and dark overrides", () => {
    expect(generated.stats).toEqual({ tokens: 4, cssVariables: 4, darkOverrides: 1 });
  });
});

describe("generateTokenFiles: typed map", () => {
  const generated = generateTokenFiles(
    documentOf({
      primitive: { color: { ink, paper } },
      semantic: {
        surface: {
          $type: "color",
          $value: "{primitive.color.paper}",
          $extensions: dark("{primitive.color.ink}"),
        },
      },
    }),
  );

  it("resolves every alias to a literal per theme", () => {
    expect(generated.ts).toContain('    "surface": "#FEFEFA",');
    expect(generated.ts).toContain('    "surface": "#141412",');
  });

  it("exports the map as const with name and theme types", () => {
    expect(generated.ts).toContain("export const tokens = {");
    expect(generated.ts).toContain("} as const;");
    expect(generated.ts).toContain("export type ThemeName = keyof typeof tokens;");
    expect(generated.ts).toContain('export type TokenName = keyof (typeof tokens)["light"];');
  });

  it("marks the file as generated", () => {
    expect(generated.ts.startsWith("/* GENERATED by frontend/scripts/build-tokens.ts")).toBe(true);
  });
});

describe("generateTokenFiles: value types", () => {
  function cssFor(
    type: string,
    value: unknown,
    extra: Record<string, unknown> = {},
  ): { css: string; ts: string } {
    return generateTokenFiles(
      documentOf({ semantic: { subject: { $type: type, $value: value }, ...extra } }),
    );
  }

  it("writes dimensions and durations with their unit", () => {
    expect(cssFor("dimension", px(12)).css).toContain("  --subject: 12px;");
    expect(cssFor("duration", { value: 120, unit: "ms" }).css).toContain("  --subject: 120ms;");
  });

  it("writes cubic beziers", () => {
    expect(cssFor("cubicBezier", [0.2, 0, 0, 1]).css).toContain(
      "  --subject: cubic-bezier(0.2, 0, 0, 1);",
    );
  });

  it("quotes multi-word font families but not single-word names or vendor keywords", () => {
    expect(
      cssFor("fontFamily", ["Overpass Variable", "Overpass", "-apple-system", "sans-serif"]).css,
    ).toContain('  --subject: "Overpass Variable", Overpass, -apple-system, sans-serif;');
  });

  it("writes numbers, font weights and plain strings through unchanged", () => {
    expect(cssFor("number", 0.42).css).toContain("  --subject: 0.42;");
    expect(cssFor("fontWeight", 800).css).toContain("  --subject: 800;");
    expect(cssFor("string", "auto").css).toContain("  --subject: auto;");
    expect(cssFor("boolean", true).css).toContain("  --subject: true;");
  });

  it("quotes url strings", () => {
    expect(cssFor("string-url", "https://tiles.example/style").css).toContain(
      '  --subject: "https://tiles.example/style";',
    );
  });

  it("resolves a dimension and a colour object to literals in the typed map", () => {
    expect(cssFor("dimension", px(12)).ts).toContain('"subject": "12px"');
    expect(generateTokenFiles(documentOf({ semantic: { c: ink } })).ts).toContain('"c": "#141412"');
  });

  it("resolves nested composite values", () => {
    const { ts } = generateTokenFiles(
      documentOf({
        primitive: { family: { $type: "fontFamily", $value: ["Overpass"] } },
        semantic: {
          typography: {
            body: {
              $type: "typography",
              $value: {
                fontFamily: "{primitive.family}",
                fontSize: px(16),
                fontWeight: 400,
                letterSpacing: px(0),
                lineHeight: 1.5,
              },
            },
          },
        },
      }),
    );
    expect(ts).toContain(
      '"typography-body": {"fontFamily":["Overpass"],"fontSize":"16px","fontWeight":400,"letterSpacing":"0px","lineHeight":1.5}',
    );
  });
});

describe("generateTokenFiles: shadows", () => {
  const layer = (alpha: number): Record<string, unknown> => ({
    color: "{primitive.shadow}",
    offsetX: px(0),
    offsetY: px(2),
    blur: px(8),
    spread: px(0),
    $alpha: alpha,
  });
  function shadowDocument(layers: unknown): Record<string, unknown> {
    return documentOf({
      primitive: { shadow: ink },
      semantic: { elevation: { $type: "shadow", $value: layers } },
    });
  }

  it("renders layers with color-mix at the layer alpha", () => {
    const { css } = generateTokenFiles(shadowDocument([layer(0.1), layer(0.08)]));
    expect(css).toContain(
      "  --elevation: 0px 2px 8px 0px color-mix(in srgb, #141412 10%, transparent), 0px 2px 8px 0px color-mix(in srgb, #141412 8%, transparent);",
    );
  });

  it("doubles the alpha in the dark blocks and clamps it at 100 percent", () => {
    const { css } = generateTokenFiles(shadowDocument([layer(0.1), layer(0.6)]));
    expect(css).toContain(
      "\n  --elevation: 0px 2px 8px 0px color-mix(in srgb, #141412 20%, transparent), 0px 2px 8px 0px color-mix(in srgb, #141412 100%, transparent);\n",
    );
  });

  it("rounds half-way percentages to the even neighbour like the reference generator", () => {
    const { css } = generateTokenFiles(shadowDocument([layer(0.165)]));
    expect(css).toContain("color-mix(in srgb, #141412 16%, transparent);");
  });

  it("renders an empty shadow as none, in both themes", () => {
    const { css } = generateTokenFiles(shadowDocument([]));
    expect(css.match(/--elevation: none;/g)).toHaveLength(3);
  });

  it("rejects a shadow that is not a list of layers", () => {
    expect(() => generateTokenFiles(shadowDocument("0 0 1px"))).toThrow(/array of shadow layers/);
  });

  it("rejects a layer without a numeric alpha", () => {
    expect(() => generateTokenFiles(shadowDocument([{ ...layer(0.1), $alpha: "0.1" }]))).toThrow(
      /numeric \$alpha/,
    );
    expect(() => generateTokenFiles(shadowDocument(["not a layer"]))).toThrow(/numeric \$alpha/);
  });

  it("rejects a layer without a colour or with a non-colour value", () => {
    const withoutColor = without(layer(0.1), "color");
    expect(() => generateTokenFiles(shadowDocument([withoutColor]))).toThrow(/missing "color"/);
    expect(() => generateTokenFiles(shadowDocument([{ ...layer(0.1), color: 12 }]))).toThrow(
      /needs a colour/,
    );
  });

  it("rejects a layer with malformed geometry", () => {
    expect(() => generateTokenFiles(shadowDocument([{ ...layer(0.1), blur: "8px" }]))).toThrow(
      /blur must be a \{value, unit\} dimension/,
    );
  });
});

describe("generateTokenFiles: typography", () => {
  const family = { $type: "fontFamily", $value: ["Overpass", "sans-serif"] };
  const weight = { $type: "fontWeight", $value: 800 };
  function typography(value: unknown): Record<string, unknown> {
    return documentOf({
      primitive: { family, weight },
      semantic: { typography: { title: { $type: "typography", $value: value } } },
    });
  }
  const full = {
    fontFamily: "{primitive.family}",
    fontSize: px(28),
    fontWeight: "{primitive.weight}",
    letterSpacing: px(-0.28),
    lineHeight: 1.1,
  };

  it("expands a composite into one custom property per part, light only", () => {
    const { css } = generateTokenFiles(typography(full));
    expect(css).toContain("  --typography-title-font-family: var(--p-family);");
    expect(css).toContain("  --typography-title-font-size: 28px;");
    expect(css).toContain("  --typography-title-font-weight: var(--p-weight);");
    expect(css).toContain("  --typography-title-letter-spacing: -0.28px;");
    expect(css).toContain("  --typography-title-line-height: 1.1;");
    expect(css.match(/--typography-title-font-size/g)).toHaveLength(1);
  });

  it("rejects a composite that is not an object or lacks a part", () => {
    expect(() => generateTokenFiles(typography("bold 16px"))).toThrow(/must be an object/);
    const partial = without(full, "lineHeight");
    expect(() => generateTokenFiles(typography(partial))).toThrow(/missing "lineHeight"/);
  });

  it("rejects a composite part that is not a scalar, alias or dimension", () => {
    expect(() => generateTokenFiles(typography({ ...full, fontSize: [16] }))).toThrow(
      /must be a string, number or boolean/,
    );
  });
});

describe("generateTokenFiles: malformed documents", () => {
  it.each([
    ["an array", []],
    ["a string", "tokens"],
    ["null", null],
  ])("rejects %s as the document", (_label, input) => {
    expect(() => generateTokenFiles(input)).toThrow(
      new TokenError("The token document must be a JSON object."),
    );
  });

  it("rejects a scalar where a token or group belongs", () => {
    expect(() => generateTokenFiles(documentOf({ semantic: { stray: "value" } }))).toThrow(
      /Expected a token or a group at semantic.stray/,
    );
  });

  it("rejects a token without a string $type", () => {
    expect(() => generateTokenFiles(documentOf({ semantic: { t: { $value: 1 } } }))).toThrow(
      /Token semantic.t has no string \$type/,
    );
  });

  it("rejects a $value that is not JSON", () => {
    expect(() =>
      generateTokenFiles(documentOf({ semantic: { t: { $type: "number", $value: undefined } } })),
    ).toThrow(/\$value that is not a JSON value/);
    expect(() =>
      generateTokenFiles(documentOf({ semantic: { t: { $type: "number", $value: [() => 1] } } })),
    ).toThrow(/\$value that is not a JSON value/);
  });

  it("rejects a dark override that is not JSON", () => {
    expect(() =>
      generateTokenFiles(
        documentOf({
          semantic: { t: { $type: "number", $value: 1, $extensions: dark(undefined) } },
        }),
      ),
    ).toThrow(/dark-mode override/);
  });

  it("ignores extensions that carry no dark override", () => {
    const { css } = generateTokenFiles(
      documentOf({
        semantic: {
          a: { $type: "number", $value: 1, $extensions: "not an object" },
          b: { $type: "number", $value: 2, $extensions: { "dev.haulcast": "nope" } },
          c: { $type: "number", $value: 3, $extensions: { "dev.haulcast": { modes: "nope" } } },
          d: { $type: "number", $value: 4, $extensions: { "dev.haulcast": { modes: {} } } },
        },
      }),
    );
    expect(css).toContain("  --a: 1;");
    expect(css).toContain("  --d: 4;");
    expect(css).not.toContain("\n    --a:");
  });

  it("rejects an unknown tier", () => {
    expect(() => generateTokenFiles({ mystery: { t: { $type: "number", $value: 1 } } })).toThrow(
      /Unknown token tier "mystery"/,
    );
  });

  it("rejects an alias to a token that does not exist", () => {
    expect(() =>
      generateTokenFiles(
        documentOf({ semantic: { t: { $type: "color", $value: "{primitive.missing}" } } }),
      ),
    ).toThrow(/Unresolved token alias \{primitive.missing\}/);
  });

  it("rejects an alias cycle", () => {
    expect(() =>
      generateTokenFiles(
        documentOf({
          semantic: {
            a: { $type: "color", $value: "{semantic.b}" },
            b: { $type: "color", $value: "{semantic.a}" },
          },
        }),
      ),
    ).toThrow(/alias cycle/);
  });

  it.each([
    ["color", 12, /has no hex value/],
    ["dimension", "12px", /must be a \{value, unit\} dimension/],
    ["duration", { value: 1 }, /must be a \{value, unit\} dimension/],
    ["cubicBezier", "ease", /array of four numbers/],
    ["cubicBezier", [{ x: 1 }], /must be a string, number or boolean/],
    ["fontFamily", "Overpass", /array of family names/],
    ["number", [1], /must be a string, number or boolean/],
  ])("rejects a %s token with value %j", (type, value, message) => {
    expect(() =>
      generateTokenFiles(documentOf({ semantic: { t: { $type: type, $value: value } } })),
    ).toThrow(message);
  });
});

describe("roundHalfToEven", () => {
  it.each([
    [0.5, 0],
    [1.5, 2],
    [2.5, 2],
    [16.5, 16],
    [17.5, 18],
    [16.2, 16],
    [16.7, 17],
    [20, 20],
  ])("rounds %f to %i", (input, expected) => {
    expect(roundHalfToEven(input)).toBe(expected);
  });
});
